export const resolveBuiltinLocaleMessage = (locale: string, id?: string) => {
  if (!id) {
    return undefined;
  }
  const messages = locale.toLowerCase().startsWith('zh')
    ? ZH_CN_BUILTIN_MESSAGES
    : EN_US_BUILTIN_MESSAGES;
  return messages[id];
};

const containsCjk = (value: string) => /[\u3400-\u9fff]/u.test(value);

/**
 * Reject a stale runtime translation only when its writing system clearly
 * conflicts with the active built-in locale. Same-language runtime overrides
 * continue to take precedence over the bundled catalog.
 */
export const isMessageCompatibleWithLocale = (
  locale: string,
  message: string,
  localizedFallback?: string,
) => {
  if (!localizedFallback) {
    return true;
  }

  const isChineseLocale = locale.toLowerCase().startsWith('zh');
  return isChineseLocale
    ? !containsCjk(localizedFallback) || containsCjk(message)
    : containsCjk(localizedFallback) || !containsCjk(message);
};
