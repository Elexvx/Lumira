package com.lumira.saas.modules.system.branding.vo;

public class BrandingSettingsVO {

    private String websiteName;
    private String websiteFaviconUrl;
    private String websiteLogoUrl;
    private String loginBackgroundUrl;
    private Boolean githubLinkEnabled;
    private String githubLinkUrl;
    private Boolean helpLinkEnabled;
    private String helpLinkUrl;
    private String companyName;
    private Integer copyrightStartYear;
    private String footerIcp;
    private String footerPoliceBeian;
    private String footerCopyright;

    public String getWebsiteName() { return websiteName; }
    public void setWebsiteName(String websiteName) { this.websiteName = websiteName; }
    public String getWebsiteFaviconUrl() { return websiteFaviconUrl; }
    public void setWebsiteFaviconUrl(String websiteFaviconUrl) { this.websiteFaviconUrl = websiteFaviconUrl; }
    public String getWebsiteLogoUrl() { return websiteLogoUrl; }
    public void setWebsiteLogoUrl(String websiteLogoUrl) { this.websiteLogoUrl = websiteLogoUrl; }
    public String getLoginBackgroundUrl() { return loginBackgroundUrl; }
    public void setLoginBackgroundUrl(String loginBackgroundUrl) { this.loginBackgroundUrl = loginBackgroundUrl; }
    public Boolean getGithubLinkEnabled() { return githubLinkEnabled; }
    public void setGithubLinkEnabled(Boolean githubLinkEnabled) { this.githubLinkEnabled = githubLinkEnabled; }
    public String getGithubLinkUrl() { return githubLinkUrl; }
    public void setGithubLinkUrl(String githubLinkUrl) { this.githubLinkUrl = githubLinkUrl; }
    public Boolean getHelpLinkEnabled() { return helpLinkEnabled; }
    public void setHelpLinkEnabled(Boolean helpLinkEnabled) { this.helpLinkEnabled = helpLinkEnabled; }
    public String getHelpLinkUrl() { return helpLinkUrl; }
    public void setHelpLinkUrl(String helpLinkUrl) { this.helpLinkUrl = helpLinkUrl; }
    public String getCompanyName() { return companyName; }
    public void setCompanyName(String companyName) { this.companyName = companyName; }
    public Integer getCopyrightStartYear() { return copyrightStartYear; }
    public void setCopyrightStartYear(Integer copyrightStartYear) { this.copyrightStartYear = copyrightStartYear; }
    public String getFooterIcp() { return footerIcp; }
    public void setFooterIcp(String footerIcp) { this.footerIcp = footerIcp; }
    public String getFooterPoliceBeian() { return footerPoliceBeian; }
    public void setFooterPoliceBeian(String footerPoliceBeian) { this.footerPoliceBeian = footerPoliceBeian; }
    public String getFooterCopyright() { return footerCopyright; }
    public void setFooterCopyright(String footerCopyright) { this.footerCopyright = footerCopyright; }
}
