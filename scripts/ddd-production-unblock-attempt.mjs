#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const repoRoot = path.resolve(path.dirname(__filename), "..");
const outputDir = process.env.DDD_PRODUCTION_UNBLOCK_ATTEMPT_DIR
  ? path.resolve(process.env.DDD_PRODUCTION_UNBLOCK_ATTEMPT_DIR)
  : path.join(repoRoot, "artifacts", "ddd", "release", "production-unblock-attempt");

const envScaffoldFile = path.join(outputDir, "release-env.local.scaffold.env");
const localReleaseEnvFile = path.join(repoRoot, ".env.release.local");
const nextActionEnvReceiptFile = path.join(outputDir, "next-action-env-receipt.attempt.json");
const laneCompletionReceiptFile = path.join(outputDir, "lane-completion-receipt.attempt.json");
const releaseEnvLintAttemptFile = path.join(outputDir, "release-env-lint.attempt.json");
const reportFile = path.join(outputDir, "production-unblock-attempt.json");
const markdownFile = path.join(outputDir, "production-unblock-attempt.md");

const templateCandidates = [
  path.join(repoRoot, "artifacts", "ddd", "release", "staging-handoff-bundle", "release-env-fill.template.env"),
  path.join(repoRoot, "artifacts", "ddd", "release", "release-env-canonical-fill.template.env"),
  path.join(repoRoot, "artifacts", "ddd", "release", "release-env-missing.template.env"),
];

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function rel(file) {
  return path.relative(repoRoot, file).replaceAll(path.sep, "/");
}

function truncate(text, max = 6000) {
  if (!text || text.length <= max) return text || "";
  return `${text.slice(0, max)}\n...[truncated ${text.length - max} chars]`;
}

function parseJson(text) {
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

function runStep(id, args, options = {}) {
  const result = spawnSync(args[0], args.slice(1), {
    cwd: repoRoot,
    env: { ...process.env, ...(options.env || {}) },
    encoding: "utf8",
    windowsHide: true,
  });
  const stdout = result.stdout || "";
  const stderr = result.stderr || "";
  return {
    id,
    command: args.join(" "),
    exitCode: typeof result.status === "number" ? result.status : null,
    signal: result.signal || null,
    ok: result.status === 0,
    parsedStdout: parseJson(stdout),
    stdout: truncate(stdout),
    stderr: truncate(stderr),
  };
}

function copyEnvScaffold() {
  const source = templateCandidates.find((candidate) => fs.existsSync(candidate));
  if (!source) {
    return {
      ok: false,
      source: null,
      artifact: rel(envScaffoldFile),
      issue: `missing release env template; checked ${templateCandidates.map(rel).join(", ")}`,
    };
  }

  const body = fs.readFileSync(source, "utf8");
  const banner = [
    "# Generated by scripts/ddd-production-unblock-attempt.mjs.",
    "# This is a scaffold, not production evidence. Replace placeholders before using it as .env.release.local.",
    "",
  ].join("\n");
  fs.writeFileSync(envScaffoldFile, `${banner}${body}`, "utf8");
  return {
    ok: true,
    source: rel(source),
    artifact: rel(envScaffoldFile),
    placeholderCount: (body.match(/__REQUIRED/g) || []).length,
  };
}

function writeLaneDraft() {
  const draft = runStep("lane-receipt-draft", ["node", "scripts/ddd-staging-execution-checklist.mjs", "--lane-receipt-draft"]);
  if (draft.parsedStdout) {
    fs.writeFileSync(laneCompletionReceiptFile, `${JSON.stringify(draft.parsedStdout, null, 2)}\n`, "utf8");
  }
  return {
    ...draft,
    artifact: fs.existsSync(laneCompletionReceiptFile) ? rel(laneCompletionReceiptFile) : null,
  };
}

function writeReport(report) {
  fs.writeFileSync(reportFile, `${JSON.stringify(report, null, 2)}\n`, "utf8");
  fs.writeFileSync(markdownFile, renderMarkdown(report), "utf8");
}

function summarizeGate(step) {
  const parsed = step?.parsedStdout;
  if (!parsed || typeof parsed !== "object") return null;
  return {
    status: parsed.status || null,
    finalRecommendation: parsed.finalRecommendation || null,
    cutoverAllowed: typeof parsed.cutoverAllowed === "boolean" ? parsed.cutoverAllowed : null,
    readyEvidenceCount: typeof parsed.readyEvidenceCount === "number" ? parsed.readyEvidenceCount : null,
    blockerCount: parsed.blockedAuditItemCount ?? parsed.blockerCount ?? null,
    nextCommand: parsed.nextCommand || null,
  };
}

function renderMarkdown(report) {
  const lines = [
    "# DDD Production Unblock Attempt",
    "",
    `Generated at: ${report.generatedAt}`,
    `Status: ${report.status}`,
    `Final recommendation: ${report.finalRecommendation}`,
    `No auto waivers: ${report.noAutoWaivers}`,
    "",
    "## Created Artifacts",
    "",
    ...report.createdArtifacts.map((artifact) => `- ${artifact}`),
    "",
    "## Result",
    "",
    report.summary,
    "",
    "## Step Status",
    "",
    "| Step | Exit | Meaning |",
    "| --- | ---: | --- |",
    ...report.steps.map((step) => `| ${step.id} | ${step.exitCode ?? "n/a"} | ${step.meaning} |`),
    "",
    "## Next Exact Commands",
    "",
    ...report.nextCommands.map((command) => `- \`${command}\``),
  ];
  return `${lines.join("\n")}\n`;
}

ensureDir(outputDir);

const createdArtifacts = [];
const envScaffold = copyEnvScaffold();
if (envScaffold.ok) createdArtifacts.push(envScaffold.artifact);
const attemptEnvFile = fs.existsSync(localReleaseEnvFile) ? localReleaseEnvFile : envScaffoldFile;
const attemptEnvSource = {
  file: rel(attemptEnvFile),
  kind: fs.existsSync(localReleaseEnvFile) ? "local-production-equivalent-env" : "placeholder-scaffold",
};

const steps = [];
steps.push({
  id: "release-env-scaffold",
  exitCode: envScaffold.ok ? 0 : 1,
  ok: envScaffold.ok,
  meaning: envScaffold.ok
    ? `created placeholder scaffold from ${envScaffold.source}; placeholders=${envScaffold.placeholderCount}`
    : envScaffold.issue,
});

const releaseEnvLint = runStep("release-env-lint-attempt-env", ["node", "scripts/ddd-release-env-file-lint.mjs"], {
  env: {
    DDD_RELEASE_ENV_FILE: attemptEnvFile,
    DDD_RELEASE_ENV_LINT_REPORT: releaseEnvLintAttemptFile,
  },
});
if (fs.existsSync(releaseEnvLintAttemptFile)) createdArtifacts.push(rel(releaseEnvLintAttemptFile));
steps.push({
  ...releaseEnvLint,
  meaning: releaseEnvLint.ok
    ? `release env lint passed for ${attemptEnvSource.file}`
    : `release env lint failed for ${attemptEnvSource.file}`,
});

const nextActionEnvCheck = runStep("next-action-env-check-attempt-env", [
  "node",
  "scripts/ddd-staging-execution-checklist.mjs",
  "--next-action-env-check",
  `--next-action-env-file=${attemptEnvFile}`,
]);
steps.push({
  ...nextActionEnvCheck,
  meaning: nextActionEnvCheck.ok
    ? `next-action env check accepted ${attemptEnvSource.file}`
    : `next-action env check rejected ${attemptEnvSource.file}`,
});

const nextActionReceipt = runStep("next-action-env-receipt-attempt", [
  "node",
  "scripts/ddd-staging-execution-checklist.mjs",
  "--next-action-env-receipt",
  `--next-action-env-file=${attemptEnvFile}`,
  `--next-action-env-receipt-output=${nextActionEnvReceiptFile}`,
]);
if (fs.existsSync(nextActionEnvReceiptFile)) createdArtifacts.push(rel(nextActionEnvReceiptFile));
steps.push({
  ...nextActionReceipt,
  meaning: nextActionReceipt.ok
    ? "wrote redacted next-action env receipt"
    : `could not write passing next-action env receipt from ${attemptEnvSource.file}`,
});

const laneDraft = writeLaneDraft();
if (laneDraft.artifact) createdArtifacts.push(laneDraft.artifact);
steps.push({
  ...laneDraft,
  meaning: laneDraft.ok
    ? "wrote current redacted lane completion draft from available fragments"
    : "could not write lane completion draft",
});

const laneContract = runStep("lane-completion-receipt-contract-attempt", [
  "node",
  "scripts/ddd-staging-execution-checklist.mjs",
  "--lane-completion-receipt-contract",
  `--lane-completion-receipt-file=${laneCompletionReceiptFile}`,
]);
steps.push({
  ...laneContract,
  meaning: laneContract.ok
    ? "lane receipt contract passes structurally"
    : "lane receipt contract failed; draft still contains incomplete lane evidence",
});

const laneCoverage = runStep("lane-completion-receipt-coverage-attempt", [
  "node",
  "scripts/ddd-staging-execution-checklist.mjs",
  "--lane-completion-receipt-coverage",
  `--lane-completion-receipt-file=${laneCompletionReceiptFile}`,
]);
steps.push({
  ...laneCoverage,
  meaning: laneCoverage.ok
    ? "lane receipt has full coverage"
    : "lane receipt coverage is incomplete",
});

const finalGate = runStep("production-evidence-readiness-enforce-attempt", [
  "node",
  "scripts/ddd-staging-execution-checklist.mjs",
  "--production-evidence-readiness-enforce",
], {
  env: {
    DDD_NEXT_ACTION_ENV_RECEIPT_FILE: nextActionEnvReceiptFile,
    DDD_LANE_COMPLETION_RECEIPT_FILE: laneCompletionReceiptFile,
  },
});
steps.push({
  ...finalGate,
  meaning: finalGate.ok
    ? "strict production evidence readiness passed"
    : "strict production evidence readiness remains blocked without real evidence",
});

const gateSummary = summarizeGate(finalGate);
const finalRecommendation = gateSummary?.finalRecommendation || "NO_GO_STRICT";
const status = finalGate.ok ? "PASS" : "BLOCKED";
const report = {
  status,
  generatedAt: new Date().toISOString(),
  finalRecommendation,
  noAutoWaivers: true,
  outputDir: rel(outputDir),
  createdArtifacts,
  envScaffold,
  attemptEnvSource,
  gateSummary,
  summary: finalGate.ok
    ? "Strict production evidence readiness passed."
    : "The loop is reduced to concrete local artifacts: a release env lint attempt, a redacted env receipt, a redacted lane receipt attempt, and strict gate output. Remaining blockers are evidence gaps reported by the strict gate.",
  nextCommands: [
    `Use ${attemptEnvSource.file} as the next env input for this attempt.`,
    "$env:DDD_RELEASE_ENV_FILE='.env.release.local'; node scripts/ddd-release-env-file-lint.mjs",
    "$env:DDD_RELEASE_ENV_FILE='.env.release.local'; node scripts/ddd-release-config-evidence.mjs",
    `node scripts/ddd-staging-execution-checklist.mjs --next-action-env-receipt --next-action-env-file=${attemptEnvSource.file} --next-action-env-receipt-output=${rel(nextActionEnvReceiptFile)}`,
    `node scripts/ddd-staging-execution-checklist.mjs --lane-completion-submission-check --lane-completion-receipt-file=${rel(laneCompletionReceiptFile)}`,
    "DDD_EXPLAIN_STRICT=true node scripts/ddd-explain-gate.mjs",
    `node scripts/ddd-staging-execution-checklist.mjs --production-evidence-readiness-enforce`,
  ],
  steps,
};

writeReport(report);

console.log(JSON.stringify({
  status: report.status,
  finalRecommendation: report.finalRecommendation,
  report: rel(reportFile),
  markdown: rel(markdownFile),
  createdArtifacts: report.createdArtifacts,
  gateSummary: report.gateSummary,
}, null, 2));

process.exit(finalGate.ok ? 0 : 1);
